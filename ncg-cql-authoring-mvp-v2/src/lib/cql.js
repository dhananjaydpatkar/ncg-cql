import { pascal, slug, outcomeById } from './model';

const q = (s) => String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
const list = (arr) => '{ ' + arr.map((v) => `'${q(v)}'`).join(', ') + ' }';
export const csUrl = (f) => f.codeSystemUrl || `http://ncgindia.org/fhir/CodeSystem/ncg-${slug(f.id)}`;

// Generates standard CQL 1.4 from the guideline model (any disease).
export function generateCql(g) {
  const L = [];
  L.push(`library ${g.id.replace(/[^A-Za-z0-9_]/g, '_')} version '${g.version}'`);
  L.push('');
  L.push('/*');
  L.push(` * ${g.title}`);
  L.push(` * Source: ${g.source || 'n/a'}`);
  L.push(` * Organization: ${g.organization}`);
  L.push(` * Status: ${g.status.toUpperCase()}`);
  L.push(' * Generated by NCG Guideline Studio. Do not edit by hand - edit the guideline instead.');
  L.push(' */');
  L.push('');
  L.push("using FHIR version '4.0.1'");
  L.push('');
  L.push("include FHIRHelpers version '4.0.1' called FHIRHelpers");
  L.push("include NCGCommon version '0.1.0' called NCGCommon");
  L.push('');

  g.findings.forEach((f) => L.push(`codesystem "${pascal(f.id)}CS": '${csUrl(f)}'`));
  L.push('');
  g.findings.forEach((f) =>
    f.values.forEach((v) => L.push(`code "${pascal(f.id)}_${pascal(v.code)}": '${q(v.code)}' from "${pascal(f.id)}CS" display '${q(v.label)}'`))
  );
  L.push('');
  L.push('context Patient');
  L.push('');
  L.push('/* ---- Findings: one observation per finding, with provenance gate ---- */');
  g.findings.forEach((f) => {
    const n = pascal(f.id);
    const retrieves = f.values.map((v) => `[Observation: "${n}_${pascal(v.code)}"]`);
    L.push(`define "${n}Observation":`);
    L.push(`  singleton from (${retrieves.join('\n    union ') || '{}'})`);
    L.push('');
    L.push(`define "${n}Known":`);
    L.push(g.enforceProvenance
      ? `  "${n}Observation" is not null and NCGCommon.IsUsable("${n}Observation")`
      : `  "${n}Observation" is not null`);
    L.push('');
    L.push(`define "${n}Value":`);
    L.push(`  "${n}Observation".code.coding[0].code`);
    L.push('');
  });

  L.push('/* ---- Rules (evaluated in order; first match wins) ---- */');
  const ruleNames = [];
  g.rules.forEach((r, i) => {
    const name = `Rule${i + 1}_${pascal(r.label).slice(0, 40)}`;
    ruleNames.push(name);
    const parts = r.conditions.map((c) => {
      const f = g.findings.find((x) => x.id === c.findingId);
      if (!f) return 'false';
      const n = pascal(f.id);
      if (c.op === 'unknown') return `not "${n}Known"`;
      return `("${n}Known" and "${n}Value" ${c.op === 'is_not' ? 'not in' : 'in'} ${list(c.values || [])})`;
    });
    L.push(`/* ${r.label} */`);
    L.push(`define "${name}":`);
    L.push('  ' + (parts.length ? parts.join('\n    and ') : 'false'));
    L.push('');
  });

  L.push('/* ---- Treatment group ---- */');
  L.push('define "TreatmentGroup":');
  L.push('  case');
  g.rules.forEach((r, i) => {
    if (r.outcomeId) L.push(`    when "${ruleNames[i]}" then '${q(r.outcomeId)}'`);
  });
  L.push(`    else '${q(g.fallbackOutcomeId)}'`);
  L.push('  end');
  L.push('');
  L.push('/* ---- Recommended regimens ---- */');
  L.push('define "RecommendedRegimens":');
  L.push('  case "TreatmentGroup"');
  g.outcomes.filter((o) => o.regimens.length).forEach((o) => {
    L.push(`    when '${q(o.id)}' then ${list(o.regimens.map((r) => r.name))}`);
  });
  L.push('    else { }');
  L.push('  end');
  L.push('');
  return L.join('\n');
}

export function generateMermaid(g) {
  const esc = (s) => String(s).replace(/"/g, "'");
  const L = ['flowchart TD', '    start([Patient data → FHIR Bundle]):::start'];
  let prev = 'start';
  g.rules.forEach((r, i) => {
    const id = `r${i + 1}`;
    L.push(`    ${id}{"${i + 1}. ${esc(r.label)}"}:::decision`);
    L.push(`    ${prev} ${i === 0 ? '-->' : '-- no -->'} ${id}`);
    const o = outcomeById(g, r.outcomeId);
    const oid = `o_${slug(r.outcomeId || 'none').replace(/-/g, '_')}`;
    L.push(`    ${id} -- yes --> ${oid}`);
    if (o) L.push(`    ${oid}[/"${esc(o.label)}"/]:::${o.kind}`);
    prev = id;
  });
  const fb = outcomeById(g, g.fallbackOutcomeId);
  L.push(`    ${prev} -- no --> fallback[/"${esc(fb?.label || 'fallback')}"/]:::${fb?.kind || 'review'}`);
  L.push('    classDef start fill:#1f2937,color:#fff,stroke:#111;');
  L.push('    classDef decision fill:#fff4cc,stroke:#c99a00,color:#000;');
  L.push('    classDef treatment fill:#d9f2e3,stroke:#2e8b57,color:#000;');
  L.push('    classDef observation fill:#e0ecff,stroke:#2b57c0,color:#000;');
  L.push('    classDef review fill:#ffe0e0,stroke:#c0392b,color:#000;');
  return L.join('\n') + '\n';
}
